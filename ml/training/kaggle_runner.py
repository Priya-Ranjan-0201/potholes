"""Kaggle Cloud Training Runner for ScamRoad.

Prepares and launches YOLOv8 model training on Kaggle GPU instances (T4 / P100).
Supports both Kaggle Notebook execution and Kaggle API batch kernel submission.
Follows SPEC B3 and project guidelines.
"""

from __future__ import annotations

import argparse
import json
import os
import textwrap
from pathlib import Path
from typing import Any


def generate_kaggle_metadata(kernel_slug: str, title: str) -> dict[str, Any]:
    """Generate kernel-metadata.json for Kaggle API kernel push."""
    username = os.environ.get("KAGGLE_USERNAME", "scamroad-surveyor")
    return {
        "id": f"{username}/{kernel_slug}",
        "title": title,
        "code_file": "kaggle_train.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_tpu": "false",
        "enable_internet": "true",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
    }


def generate_kaggle_script_content() -> str:
    """Generate standalone self-contained training script for Kaggle GPU environments."""
    return textwrap.dedent("""\
        # ScamRoad Kaggle GPU Training Pipeline (YOLOv8n / YOLOv8s)
        # Auto-generated by ml/training/kaggle_runner.py

        import os
        import sys
        import subprocess
        from pathlib import Path

        print("=== ScamRoad Kaggle Training Pipeline ===")
        print(f"Working Directory: {os.getcwd()}")

        # 1. Install Ultralytics and dependencies
        subprocess.check_call(
            [sys.executable, "-m", "pip", "install", "-q", "ultralytics", "pyyaml"]
        )

        import torch
        from ultralytics import YOLO

        print(f"PyTorch Version: {torch.__version__}")
        print(f"CUDA Available: {torch.cuda.is_available()}")
        if torch.cuda.is_available():
            dev_name = torch.cuda.get_device_name(0)
            mem_b = torch.cuda.get_device_properties(0).total_memory
            vram_gb = round(mem_b / (1024**3), 2)
            print(f"GPU: {dev_name} | VRAM: {vram_gb} GB")

        # 2. Output and artifacts setup
        output_dir = Path("/kaggle/working/scam_road")
        output_dir.mkdir(parents=True, exist_ok=True)

        # 3. Download or prepare dataset
        data_cfg = {
            "path": "/kaggle/working/data",
            "train": "splits/train.txt",
            "val": "splits/val.txt",
            "test": "splits/test.txt",
            "nc": 4,
            "names": {
                0: "pothole",
                1: "crack_longitudinal",
                2: "crack_transverse",
                3: "crack_alligator",
            },
        }
        import yaml

        cfg_path = output_dir / "dataset.yaml"
        with open(cfg_path, "w", encoding="utf-8") as f:
            yaml.dump(data_cfg, f)

        # 4. Initialize YOLOv8n
        print("Initializing YOLOv8n backbone...")
        model = YOLO("yolov8n.pt")

        # 5. Launch Training (100 epochs, batch 16, GPU 0)
        print("Launching YOLOv8n training...")
        results = model.train(
            data=str(cfg_path),
            epochs=100,
            batch=16,
            imgsz=640,
            device=0 if torch.cuda.is_available() else "cpu",
            project=str(output_dir / "runs"),
            name="pothole_yolov8n",
            optimizer="AdamW",
            lr0=0.001,
            lrf=0.01,
            save=True,
            plots=True,
        )

        print("Training complete! Model checkpoints saved in /kaggle/working/scam_road/runs.")
        """)


def create_kaggle_bundle(output_dir: Path, kernel_slug: str = "scamroad-yolov8-training") -> Path:
    """Create a directory bundle ready to be pushed with `kaggle kernels push`."""
    output_dir.mkdir(parents=True, exist_ok=True)

    metadata = generate_kaggle_metadata(kernel_slug, title="ScamRoad Pothole Detector Training")
    with (output_dir / "kernel-metadata.json").open("w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    script_content = generate_kaggle_script_content()
    with (output_dir / "kaggle_train.py").open("w", encoding="utf-8") as f:
        f.write(script_content)

    return output_dir


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse CLI arguments."""
    parser = argparse.ArgumentParser(description="Kaggle training preparation utility.")
    parser.add_argument(
        "--bundle-dir",
        type=Path,
        default=Path("ml/training/kaggle_bundle"),
        help="Target directory for Kaggle kernel bundle.",
    )
    parser.add_argument(
        "--slug",
        type=str,
        default="scamroad-yolov8-training",
        help="Kaggle kernel slug.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    """Entry-point for Kaggle preparation CLI."""
    args = parse_args(argv)
    bundle_path = create_kaggle_bundle(args.bundle_dir, kernel_slug=args.slug)
    print(f"Kaggle kernel bundle created at: {bundle_path.resolve()}")
    print("To push to Kaggle:")
    print(f"  kaggle kernels push -p {bundle_path}")


if __name__ == "__main__":
    main()
