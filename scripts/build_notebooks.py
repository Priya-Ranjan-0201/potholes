def main() -> None:
    nb_dir = Path("notebooks")
    nb_dir.mkdir(parents=True, exist_ok=True)

    colab_nb = build_colab_notebook()
    colab_path = nb_dir / "colab_train.ipynb"
    with open(colab_path, "w", encoding="utf-8") as f:
        json.dump(colab_nb, f, indent=2)
